/**
 * recording.ts — the beats the simulated sensor plays back.
 *
 * WHY A REAL RECORDING AND NOT RANDOM NUMBERS. The simulator used to emit
 * `857 + random`, which is enough to prove the plumbing works and useless for
 * anything else: RMSSD wanders around a constant, every question scores the
 * same, and a demo of a stress-detection system detects no stress. Nothing in a
 * screenshot of it would be wrong, and nothing would be interesting either.
 *
 * These are real inter-beat intervals from WESAD subject S2, in milliseconds:
 * the last nine minutes of the seated resting phase, followed by the whole TSST
 * — a genuine social-evaluative stressor, the closest thing in any public
 * dataset to a job interview. So the label moves for the reason it is supposed
 * to move, and a person watching the demo sees the system do its actual job.
 *
 * The shape is deliberate, and the resting head is long on purpose. Nine minutes
 * cover the two-minute baseline, whatever prelude piles up while the sensor sits
 * connected, AND the first questions; the ten TSST minutes then run underneath
 * the rest of them. Early questions land on the tail of the rest and read low,
 * later ones land on the stressor and read high — an interview that gets harder,
 * which is the thing worth showing.
 *
 * A shorter head was tried first and ran out: with six questions paced like the
 * real protocol the timeline reached minute 18 of a fourteen-minute recording,
 * and the last two questions were scored against nothing at all.
 *
 * DEV MODE ONLY. Nothing here is reachable without `?dev=1`, and the simulation
 * is behind that flag rather than being an automatic fallback for the same
 * reason it always was: inventing beats when a real sensor fails would produce
 * a complete, confident report about a person from data describing nobody.
 */


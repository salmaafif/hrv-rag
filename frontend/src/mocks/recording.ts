/**
 * How much faster than real time the simulation runs.
 *
 * A full V3 session is roughly fifteen minutes. At real speed nobody will sit
 * through that to check a layout change, and no examiner will sit through it at
 * all — which made the simulated device unusable for the one thing it exists
 * for.
 *
 * TEN, NOT MORE. The number is bounded on both sides. Too slow and the demo is
 * useless; too fast and a session outruns the nineteen minutes of recording
 * above, after which the sensor stops and the last questions land on nothing.
 * At 10x a full six-question session takes about two minutes of real time and
 * still leaves recording in hand for somebody who reads each question slowly.
 *
 * BOTH CLOCKS MUST USE IT. The session clock in `SessionPage` scales by exactly
 * this factor too. If only the beats were accelerated, the timeline would say a
 * question was answered at second 90 while the beats had already run on to
 * minute 15, and every question window would be scored against the wrong
 * stretch of recording — silently, and with entirely plausible-looking numbers.
 */
export const SIMULATION_SPEED = 10
